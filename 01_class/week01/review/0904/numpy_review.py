# [문제 2] 0~3차원 + ndim
# 0차원(100), 1차원([1,2,3]), 2차원([[1,2,3],[4,5,6]]),
# 3차원([[[1,2,3],[4,5,6]],[[1,2,3],[4,5,6]]]) 을 만들고 각각 .ndim 출력.

arr0 = np.array(100)    # 대괄호의 개수는 차원의 개수를 뜻함 : cf. [ 1개 - 1차원 배열
arr1 = np.array([1,2,3])    
arr2 = np.array([[1,2,3], [4,5,6]])
arr3 = np.array([[[1,2,3], [4,5,6]], [[1,2,3], [4,5,6]]])

print("=== 문제 2 ===")
print(arr0.ndim)    # 배열의 차원의 개수는 ndim으로 확인 (이 배열은 몇 차원인가?)
print(arr1.ndim)
print(arr2.ndim)
print(arr3.ndim)

# [답]
# 0
# 1
# 2
# 3
